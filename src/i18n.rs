use std::sync::Mutex;

// ============================================================
// Supported languages (English is the default and fallback).
// ============================================================

#[derive(Clone, Copy, PartialEq, Debug)]
pub enum Language {
    En,
    Ru,
    Es,
    Fr,
    De,
    Pt,
    It,
    Pl,
    Tr,
    Uk,
    Zh,
    Ja,
    Ko,
}

impl Language {
    pub fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Ru => "ru",
            Self::Es => "es",
            Self::Fr => "fr",
            Self::De => "de",
            Self::Pt => "pt",
            Self::It => "it",
            Self::Pl => "pl",
            Self::Tr => "tr",
            Self::Uk => "uk",
            Self::Zh => "zh",
            Self::Ja => "ja",
            Self::Ko => "ko",
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code {
            "ru" => Self::Ru,
            "es" => Self::Es,
            "fr" => Self::Fr,
            "de" => Self::De,
            "pt" => Self::Pt,
            "it" => Self::It,
            "pl" => Self::Pl,
            "tr" => Self::Tr,
            "uk" => Self::Uk,
            "zh" => Self::Zh,
            "ja" => Self::Ja,
            "ko" => Self::Ko,
            _ => Self::En,
        }
    }

    /// Name shown in the language picker (in the language itself).
    pub fn native_name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Ru => "Русский",
            Self::Es => "Español",
            Self::Fr => "Français",
            Self::De => "Deutsch",
            Self::Pt => "Português",
            Self::It => "Italiano",
            Self::Pl => "Polski",
            Self::Tr => "Türkçe",
            Self::Uk => "Українська",
            Self::Zh => "中文",
            Self::Ja => "日本語",
            Self::Ko => "한국어",
        }
    }

    pub fn all() -> &'static [Language] {
        &[
            Self::En,
            Self::Ru,
            Self::Es,
            Self::Fr,
            Self::De,
            Self::Pt,
            Self::It,
            Self::Pl,
            Self::Tr,
            Self::Uk,
            Self::Zh,
            Self::Ja,
            Self::Ko,
        ]
    }
}

// ============================================================
// Current language (shared state).
// ============================================================

static CURRENT: Mutex<Language> = Mutex::new(Language::En);

pub fn set(lang: Language) {
    *CURRENT.lock().unwrap() = lang;
}

pub fn current() -> Language {
    *CURRENT.lock().unwrap()
}

pub fn set_from_code(code: &str) {
    set(Language::from_code(code));
}

